    /** 질문으로 볼 만한 말인지 (띄어쓰기·물음표 무시) */
    private fun norm(t: String) = t.replace(Regex("[\\s.,?!~]"), "")

    /** 질문에 맞는 대답. 못 찾으면 null */
    fun find(question: String): Entry? {
        val q = norm(question)
        if (q.length < 2) return null
        return entries
            .map { e -> e to (e.keys.count { q.contains(it) } * 2 + e.boost.count { q.contains(it) }) }
            .filter { (e, score) -> score >= 2 && e.keys.any { q.contains(it) } }
            .maxByOrNull { it.second }?.first
    }

